const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
(async () => {
  const browser = await chromium.launch({headless: true, channel: process.env.BROWSER_CHANNEL || 'chrome'});
  try {
    const context = await browser.newContext({viewport: {width: 390, height: 844}});
    await context.addCookies([{name: 'sessionid', value: process.env.JOURNAL_BROWSER_SESSION, url: process.env.JOURNAL_BROWSER_URL}]);
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(process.env.JOURNAL_BROWSER_URL);
    await page.getByRole('button', {name: 'Write an entry'}).click();
    await page.getByLabel('Daily summary').fill('Alex tried a new classroom activity.');
    await page.getByLabel('Observations').fill('Stayed curious and asked for a break.');
    await page.getByLabel('What helped').fill('A visual schedule.');
    await page.getByRole('button', {name: 'Save draft'}).click();
    await page.getByRole('status').filter({hasText: 'Saved on the server'}).waitFor();
    const editUrl = page.url();
    await page.reload();
    assert.equal(await page.getByLabel('Daily summary').inputValue(), 'Alex tried a new classroom activity.');
    await context.setOffline(true);
    await page.getByLabel('Daily summary').fill('Text preserved while offline.');
    await page.getByRole('button', {name: 'Save draft'}).click();
    await page.getByRole('status').filter({hasText: 'Save not confirmed'}).waitFor();
    assert.equal(await page.getByLabel('Daily summary').inputValue(), 'Text preserved while offline.');
    await context.setOffline(false);
    await page.getByRole('button', {name: 'Save draft'}).click();
    await page.getByRole('status').filter({hasText: 'Saved on the server'}).waitFor();
    await page.getByRole('button', {name: 'Review audience'}).click();
    await page.getByRole('heading', {name: 'Who can read this?'}).waitFor();
    await page.getByRole('checkbox').check();
    await page.getByRole('button', {name: 'Confirm & submit'}).click();
    await page.getByRole('heading', {name: 'School moments'}).waitFor();
    await page.getByLabel('Add a comment').fill('A useful observation for tomorrow.');
    await page.getByRole('button', {name: 'Post comment'}).click();
    await page.getByText('A useful observation for tomorrow.', {exact:true}).waitFor();
    await page.getByRole('link', {name: 'Edit your entry'}).click();
    await page.getByLabel('Daily summary').fill('Revised after a conversation.');
    await page.getByRole('button', {name: 'Review audience'}).click();
    await page.getByRole('checkbox').check();
    await page.getByRole('button', {name: 'Confirm & submit'}).click();
    await page.getByText(/Version \d+ · Replaced/).waitFor();
    await page.getByRole('link', {name: 'Back to journal'}).click();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.evaluate(async () => { await navigator.serviceWorker.ready; });
    const keys = await page.evaluate(async () => {const result=[];for (const name of await caches.keys()) for(const req of await (await caches.open(name)).keys()) result.push(new URL(req.url).pathname);return result;});
    assert.ok(keys.length >= 5, JSON.stringify(keys));
    assert.ok(keys.every(key => ['/static/app.css','/static/app.js','/static/offline.html','/static/icon-192.png','/static/icon-512.png'].includes(key)), JSON.stringify(keys));
    assert.equal(await page.evaluate(() => localStorage.length), 0);
    fs.mkdirSync('test-results', {recursive:true});
    await page.screenshot({path: 'test-results/mobile-timeline.png', fullPage:true});
    await page.setViewportSize({width:1280,height:900});
    await page.screenshot({path:'test-results/desktop-timeline.png',fullPage:true});
    await context.setOffline(true);
    await page.goto(process.env.JOURNAL_BROWSER_URL + '/?offline-check');
    await page.getByRole('heading', {name: 'You’re offline'}).waitFor();
    assert.ok(!(await page.content()).includes('Revised after a conversation.'));
    assert.deepEqual(errors, []);
    console.log('PASS: mobile write/save/reload/offline retry/review/publish/comment/revise; responsive widths; public-only cache; generic offline navigation.');
  } finally {await browser.close();}
})().catch(error => {console.error(error);process.exit(1);});
